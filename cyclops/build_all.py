"""Build the whole corrupted-cyclops roster for Roblox.

Run:  python3 cyclops/build_all.py [--no-render]     (needs `pip install bpy==4.2.0 pillow`)

Outputs
  export/cyclops_texture.png        shared 1024 px texture atlas (also embedded in every FBX)
  export/outfits/<Outfit>.fbx       R15 outfit pieces named <R15Part>_<Kind>
  export/weapons/<Weapon>.fbx       weapon parts (Handle + others)
  (wolves: see wolf_rig.py -> export/creatures/)
  roblox/CyclopsData.lua            generated sizes/offsets/joints for every model
  renders/*.png                     preview lineups
"""
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import bpy  # noqa: E402
from mathutils import Matrix, Vector  # noqa: E402

import kit  # noqa: E402
from kit import R15_POS, R15_SIZE, Piece, export_fbx, lua_vec, piece_bounds  # noqa: E402

EXPORT_DIR = os.path.join(HERE, "export")
RENDER_DIR = os.path.join(HERE, "renders")
ROBLOX_DIR = os.path.join(HERE, "roblox")


def make_materials(img):
    def mat(name, emission):
        m = bpy.data.materials.new(name)
        m.use_nodes = True
        nodes = m.node_tree.nodes
        bsdf = nodes["Principled BSDF"]
        tex = nodes.new("ShaderNodeTexImage")
        tex.image = img
        m.node_tree.links.new(tex.outputs["Color"], bsdf.inputs["Base Color"])
        bsdf.inputs["Metallic"].default_value = 0.0 if emission else 0.3
        bsdf.inputs["Roughness"].default_value = 0.6
        if emission:
            m.node_tree.links.new(tex.outputs["Color"], bsdf.inputs["Emission Color"])
            bsdf.inputs["Emission Strength"].default_value = 4.0
        return m
    return mat("Cyclops", False), mat("CyclopsGlow", True)


# ---------------------------------------------------------------------------
def build_outfit_objects(outfit, mats):
    objs = []
    for part, kinds in outfit.pieces.items():
        for kind, piece in kinds.items():
            if not len(piece.bm.faces):
                piece.bm.free()
                continue
            mat = mats[1] if kind.endswith("Glow") else mats[0]
            obj = piece.to_object(f"{part}_{kind}", mat, R15_POS[part])
            obj["outfit"] = outfit.name
            objs.append(obj)
    return objs


def release_names(objs, prefix):
    """Rename exported objects so the next model can reuse the exact piece names
    (Blender would otherwise export "Head_Armor.001")."""
    for o in objs:
        o.name = f"{prefix}:{o.name}"
        o.data.name = o.name


def lua_color(rgb):
    return f"Color3.fromRGB({rgb[0]}, {rgb[1]}, {rgb[2]})"


def lua_outfit(outfit, objs):
    lines = [f'\t\t{outfit.name} = {{', f'\t\t\tglow = {lua_color(outfit.glow)},', '\t\t\tpieces = {']
    for o in sorted(objs, key=lambda o: o.name):
        size, offset = piece_bounds(o)
        lines.append(f'\t\t\t\t["{o.name}"] = {{ size = {lua_vec(size)}, offset = {lua_vec(offset)} }},')
    lines += ['\t\t\t},', '\t\t},']
    return "\n".join(lines)


def lua_weapon(weapon, objs):
    lines = [f'\t\t{weapon.name} = {{',
             f'\t\t\tdamage = {weapon.damage}, cooldown = {weapon.cooldown}, twoHanded = {str(weapon.two_handed).lower()},'
             f' bleed = {str(getattr(weapon, "bleed", False)).lower()},',
             f'\t\t\tglow = {lua_color(weapon.glow)},',
             f'\t\t\tgrip = CFrame.Angles({", ".join(f"math.rad({a})" for a in weapon.grip)}),',
             '\t\t\tpieces = {']
    for o in sorted(objs, key=lambda o: o.name):
        size, offset = piece_bounds(o)
        lines.append(f'\t\t\t\t["{o.name}"] = {{ size = {lua_vec(size)}, offset = {lua_vec(offset)} }},')
    lines += ['\t\t\t},', '\t\t},']
    return "\n".join(lines)


def write_data(outfit_lua, weapon_lua, creature_lua):
    sizes = "\n".join(f'\t\t{name} = Vector3.new({", ".join(f"{v:g}" for v in s)}),'
                      for name, s in R15_SIZE.items())
    text = f"""-- Generated by cyclops/build_all.py - do not edit by hand.
-- Sizes/offsets are in studs, relative to the R15 body part (outfits), the weapon's
-- grip origin (weapons) or the creature's origin (creatures).
return {{
\tblockSize = {{
{sizes}
\t}},
\toutfits = {{
{chr(10).join(outfit_lua)}
\t}},
\tweapons = {{
{chr(10).join(weapon_lua)}
\t}},
\tcreatures = {{
{chr(10).join(creature_lua)}
\t}},
}}
"""
    with open(os.path.join(ROBLOX_DIR, "CyclopsData.lua"), "w") as fh:
        fh.write(text)


